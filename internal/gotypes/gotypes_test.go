func TestGoListFails(t *testing.T) {
	root := module(t, "1.25.0", map[string]string{"a/a.go": "package a\n"})
	mod := filepath.Join(root, "go.mod")
	b, _ := os.ReadFile(mod)
	os.WriteFile(mod, append(b, "require example.org/missing\n"...), 0o644) // no version
	_, got := run(t, root, nil)
	if !strings.HasPrefix(got, "go list failed: ") || !strings.HasSuffix(got, "  fix: run go mod tidy, and make sure go build works\n") {
		t.Errorf("got %q", got)
	}
}

// TestTime is the measure of step 4: three apps that import what views
// will. It logs; the budget is D-65's, and the plan records the numbers.
func TestTime(t *testing.T) {
	files := map[string]string{}
	for _, app := range []string{"a", "b", "c"} {
		files[app+"/views.go"] = "package " + app + `

import (
	"context"
	"database/sql"
	"html/template"
	"net/http"

	"github.com/maago-web/maago"
)

type Post struct {
	maago.Model
	ID    int64
	Title string
}

type Page struct {
	Posts []Post
	Body  template.HTML
}

func List(ctx context.Context, db *sql.DB) (Page, error) { _ = http.StatusOK; return Page{}, nil }
`
	}
	root := module(t, "1.25.0", files)
	run(t, root, nil) // fill the build cache
	start := time.Now()
	if _, out := run(t, root, nil); out != "" {
		t.Fatal(out)
	}
	t.Logf("Check of three apps: %v", time.Since(start))
}
