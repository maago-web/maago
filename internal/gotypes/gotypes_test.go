// match compares got with want, where "…" in want stands for the rest of
// its line (go list's own words).
func match(got, want string) bool {
	g, w := strings.Split(got, "\n"), strings.Split(want, "\n")
	if len(g) != len(w) {
		return false
	}
	for i := range w {
		before, _, cut := strings.Cut(w[i], "…")
		if cut && strings.HasPrefix(g[i], before) || !cut && g[i] == w[i] {
			continue
		}
		return false
	}
	return true
}

