const marker = "// Code generated by maago. DO NOT EDIT.\n"

// module writes a module that requires the runtime of this repository,
// with files beside go.mod, and returns its root.
func module(t *testing.T, goVersion string, files map[string]string) string {
	t.Helper()
	repo, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	root := t.TempDir()
	files["go.mod"] = "module example.com/app\n\ngo " + goVersion + "\n\nrequire github.com/maago-web/maago v0.0.0\n\nreplace github.com/maago-web/maago => " + repo + "\n"
	for name, src := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// run checks the module and returns its diagnostics as maago prints them.
func run(t *testing.T, root string, overlay map[string]string) (*Result, string) {
	t.Helper()
	o := map[string][]byte{}
	for k, v := range overlay {
		o[k] = []byte(v)
	}
	r, ds := Check(root, o)
	var b strings.Builder
	diag.Write(&b, ds)
	return r, b.String()
}

func TestOverlay(t *testing.T) {
	files := map[string]string{
		"a/models_gen.go": marker + "package a\n\nfunc Stale() {}\n",
		"a/old_gen.go":    marker + "package a\n\nfunc Fresh() {}\n", // gen removes it
		"a/mine_gen.go":   "package a\n\nfunc Mine() {}\n",           // no marker: the user's (D-67)
		"a/tool.go":       "//go:build ignore\n\npackage a\n\nfunc broken( {\n",
		"a/a.go":          "package a\n\nfunc use() { Fresh(); Mine() }\n",
	}
	overlay := map[string]string{"a/models_gen.go": marker + "package a\n\nfunc Fresh() {}\n"}
	if _, out := run(t, module(t, "1.25.0", files), overlay); out != "" {
		t.Errorf("fresh overlay:\n%s", out)
	}

	files["a/a.go"] = "package a\n\nfunc use() { Stale() }\n"
	_, out := run(t, module(t, "1.25.0", files), overlay)
	want := "a/a.go:3:14: undefined: Stale\n  fix: go build reports the same error; fix it there\n"
	if out != want {
		t.Errorf("stale disk file seen:\ngot  %q\nwant %q", out, want)
	}
}

func TestPackages(t *testing.T) {
	root := module(t, "1.25.0", map[string]string{
		"a/a.go": "package a\n\nimport \"github.com/maago-web/maago\"\n\ntype Post struct {\n\tmaago.Model\n\tID int64\n}\n",
		"b/b.go": `package b

import (
	"html/template"
	"net/http"

	"example.com/app/a"
)

type Page struct {
	Post a.Post
	Body template.HTML
}

var _ = http.StatusOK
`,
		"c/c.go": "package c\n\n// int one() { return 1; }\nimport \"C\"\n\nvar N C.int = C.one()\n",
		"d/d.go": "package d\n\nimport \"unsafe\"\n\nvar S = unsafe.Sizeof(0)\n",
	})
	r, out := run(t, root, nil)
	if out != "" {
		t.Fatalf("errors:\n%s", out)
	}
	page := r.Packages["b"].Scope().Lookup("Page")
	if page == nil {
		t.Fatal("no Page in b")
	}
	if got := page.Type().Underlying().String(); got != "struct{Post example.com/app/a.Post; Body html/template.HTML}" {
		t.Errorf("Page = %s", got)
	}
	for dir, name := range map[string]string{"c": "N", "d": "S"} {
		if r.Packages[dir].Scope().Lookup(name) == nil {
			t.Errorf("no %s in %s", name, dir)
		}
	}
}

