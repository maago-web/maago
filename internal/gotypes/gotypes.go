// Package gotypes type-checks the packages of the user's project with
// go/types, seeing the files maago is about to generate instead of those
// on disk (D-117). Packages outside the project come from the export data
// the go command leaves in its build cache.
package gotypes

import (
	"bytes"
	"cmp"
	"encoding/json"
	"errors"
	"go/ast"
	"go/importer"
	"go/parser"
	"go/scanner"
	"go/token"
	"go/types"
	"io"
	"maps"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"slices"
	"strconv"
	"strings"

	"github.com/maago-web/maago/internal/diag"
	"github.com/maago-web/maago/internal/pipeline"
)

// Result is the checked packages, by directory (a slash path relative to
// the project root), and the file set their positions are in.
type Result struct {
	Fset     *token.FileSet
	Packages map[string]*types.Package
}

// listed is what go list tells of a package.
type listed struct {
	Dir, ImportPath, Export string
	GoFiles, CgoFiles       []string
	DepsErrors              []struct{ Err string }
	IgnoredGoFiles          []string
	Module                  *struct{ Path, GoVersion string }
	Error                   *struct{ Err string }
}

// pkg is a project package on its way through Check.
type pkg struct {
	dir, path string
	ignored   []string // files a build constraint leaves out
	files     []*ast.File
	state     int // 0 not yet checked, 1 being checked, 2 done
	failed    bool
	types     *types.Package
}

// Check type-checks every package of the project at root. overlay holds
// the generated files maago is about to write, by slash path relative to
// root; they replace the generated files on disk, and a generated file on
// disk that overlay lacks is left out, since gen removes it (D-60).
// overlay holds only maago's own .go files, so none has a build
// constraint, cgo, or is a test. Packages are checked one after another.
// root is absolute, as project.Root returns it.
func Check(root string, overlay map[string][]byte) (*Result, []diag.Diagnostic) {
	list, ds := goList(root, "-e", "-json=Dir,ImportPath,GoFiles,CgoFiles,IgnoredGoFiles,Module", "./...")
	if len(ds) > 0 {
		return nil, ds
	}
	fset := token.NewFileSet()
	pkgs := map[string]*pkg{} // by import path
	byDir := map[string]*pkg{}
	var goVersion, modulePath string
	for _, l := range list {
		rel, err := filepath.Rel(root, l.Dir)
		if err != nil {
			return nil, bug("go list reported " + l.Dir + " outside " + root)
		}
		p := &pkg{dir: filepath.ToSlash(rel), path: l.ImportPath}
		if l.Module != nil {
			goVersion, modulePath = "go"+l.Module.GoVersion, l.Module.Path
		}
		for _, f := range l.IgnoredGoFiles {
			if !strings.HasSuffix(f, "_test.go") {
				p.ignored = append(p.ignored, path.Join(p.dir, f))
			}
		}
		for _, f := range append(slices.Clone(l.GoFiles), l.CgoFiles...) {
			name := path.Join(p.dir, f)
			src, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(name)))
			if err != nil {
				ds = append(ds, diag.New(token.Position{Filename: name}, "cannot read file: "+diag.OneLine(err.Error()), "make sure the file can be read"))
				continue
			}
			if pipeline.IsGenerated(src) {
				continue // gen replaces or removes it
			}
			if _, ok := overlay[name]; ok { // the words of pipeline.Check, which comes later
				ds = append(ds, diag.New(token.Position{Filename: name}, "file was not generated by maago, but maago generates a file at this path", "rename or move this file"))
				p.failed = true
				continue
			}
			ds = append(ds, p.parse(fset, name, src, "fix the Go syntax; go build reports the same error")...)
		}
		pkgs[p.path], byDir[p.dir] = p, p
	}
	for _, name := range slices.Sorted(maps.Keys(overlay)) {
		p := byDir[path.Dir(name)]
		if p == nil {
			ds = append(ds, diag.New(token.Position{Filename: name}, "generated file is in no package go list knows", "report this as a maago bug"))
			continue
		}
		ds = append(ds, p.parse(fset, name, overlay[name], "report this as a maago bug")...)
	}
	// A package that failed to parse is not checked, and neither is what
	// imports it; the others are (D-61).
	exports, eds := exportData(fset, root, modulePath, pkgs)
	if len(eds) > 0 {
		return nil, append(ds, eds...)
	}
	c := &checker{fset: fset, pkgs: pkgs, overlay: overlay, goVersion: goVersion}
	c.gc = importer.ForCompiler(fset, "gc", func(path string) (io.ReadCloser, error) {
		f, ok := exports[path]
		if !ok {
			return nil, errors.New("no export data") // exportData reported it
		}
		return os.Open(f)
	})
	for _, dir := range slices.Sorted(maps.Keys(byDir)) {
		c.check(byDir[dir])
	}
	if ds = append(ds, c.ds...); len(ds) > 0 {
		return nil, ds
	}
	r := &Result{Fset: fset, Packages: map[string]*types.Package{}}
	for dir, p := range byDir {
		r.Packages[dir] = p.types
	}
	return r, nil
}

// parse adds the file name, src, to p. A syntax error fails p, with fix.
func (p *pkg) parse(fset *token.FileSet, name string, src []byte, fix string) []diag.Diagnostic {
	f, err := parser.ParseFile(fset, name, src, parser.SkipObjectResolution)
	var list scanner.ErrorList
	if errors.As(err, &list) {
		p.failed = true
		var ds []diag.Diagnostic
		for _, e := range list {
			ds = append(ds, diag.New(e.Pos, diag.OneLine(e.Msg), fix))
		}
		return ds
	}
	p.files = append(p.files, f)
	return nil
}

// exportData finds the export data of every package the project imports
// from outside itself. An import that go list cannot build is an error at
// its first place.
func exportData(fset *token.FileSet, root, modulePath string, pkgs map[string]*pkg) (map[string]string, []diag.Diagnostic) {
	first := map[string]token.Pos{}
	for _, p := range pkgs {
		for _, f := range p.files {
			for _, spec := range f.Imports {
				ip, _ := strconv.Unquote(spec.Path.Value)
				if pkgs[ip] != nil || ip == "C" || ip == "unsafe" {
					continue
				}
				if pos, ok := first[ip]; !ok || spec.Path.Pos() < pos {
					first[ip] = spec.Path.Pos()
				}
			}
		}
	}
	if len(first) == 0 {
		return nil, nil
	}
	list, ds := goList(root, append([]string{"-e", "-deps", "-export", "-json=ImportPath,Export,Error,DepsErrors"}, slices.Sorted(maps.Keys(first))...)...)
	if len(ds) > 0 {
		return nil, ds
	}
	exports, failed := map[string]string{}, map[string]string{}
	broken := map[string]bool{} // builds not, for a package it imports
	for _, l := range list {
		switch {
		case l.Error != nil:
			failed[l.ImportPath], _, _ = strings.Cut(l.Error.Err, "\n")
		case l.Export != "":
			exports[l.ImportPath] = l.Export
		case len(l.DepsErrors) > 0:
			failed[l.ImportPath], _, _ = strings.Cut(l.DepsErrors[0].Err, "\n")
			broken[l.ImportPath] = true
		}
	}
	for ip, pos := range first {
		if exports[ip] != "" {
			continue
		}
		msg := cmp.Or(failed[ip], "no export data")
		fix := "add the module with go get " + ip
		switch {
		case broken[ip]:
			fix = "the package imports what cannot be found; run go mod tidy, or fix that package"
		case ip == modulePath || strings.HasPrefix(ip, modulePath+"/"):
			fix = "no such package in this module; check the import path"
		}
		ds = append(ds, diag.New(fset.Position(pos), "cannot import "+strconv.Quote(ip)+": "+diag.OneLine(msg), fix))
	}
	return exports, ds
}

// checker is the state of one Check: the packages checked so far and the
// errors found.
type checker struct {
	fset      *token.FileSet
	pkgs      map[string]*pkg
	overlay   map[string][]byte
	goVersion string
	gc        types.Importer
	ds        []diag.Diagnostic
}

// check type-checks p after the project packages it imports. A package
// that imports one that failed is not checked: its errors would only
// follow from the other's (D-61).
func (c *checker) check(p *pkg) {
	if p.state != 0 {
		return
	}
	p.state = 1
	for _, f := range p.files {
		for _, spec := range f.Imports {
			ip, _ := strconv.Unquote(spec.Path.Value)
			dep := c.pkgs[ip]
			if dep == nil {
				continue
			}
			if dep.state == 1 {
				c.ds = append(c.ds, diag.New(c.fset.Position(spec.Path.Pos()), "import cycle: "+strconv.Quote(ip)+" imports "+strconv.Quote(p.path)+", directly or not",
					"move what both need into a third package"))
				p.failed = true
				continue
			}
			c.check(dep)
			if dep.failed {
				p.failed = true
			}
		}
	}
	p.state = 2
	if p.failed {
		return
	}
	var errs []types.Error
	conf := types.Config{
		GoVersion:   c.goVersion,
		FakeImportC: true, // C.x is of unknown type, not an error
		Importer:    importerFunc(c.importPkg),
		Error:       func(err error) { errs = append(errs, err.(types.Error)) },
	}
	p.types, _ = conf.Check(p.path, c.fset, p.files, nil)
	for _, e := range errs {
		c.ds = append(c.ds, c.diagnose(p, e))
	}
	p.failed = len(errs) > 0
}

// importPkg returns a project package checked before, or the export data
// of any other.
func (c *checker) importPkg(ip string) (*types.Package, error) {
	if p := c.pkgs[ip]; p != nil {
		return p.types, nil
	}
	return c.gc.Import(ip)
}

// diagnose turns a type error into a diagnostic. An error in generated
// code is maago's, unless the package has files a build constraint leaves
// out: the models and queries are read without build constraints, so the
// generated code may use what only those files declare.
func (c *checker) diagnose(p *pkg, e types.Error) diag.Diagnostic {
	pos := c.fset.Position(e.Pos)
	msg := diag.OneLine(strings.ReplaceAll(e.Msg, "\n\t", "; ")) // "not enough arguments…\n\thave …\n\twant …"
	if _, generated := c.overlay[pos.Filename]; !generated {
		return diag.New(pos, msg, caseHint(p, msg)+"go build reports the same error; fix it there")
	}
	if len(p.ignored) > 0 {
		return diag.New(pos, msg, "generated code cannot see what files with a build constraint declare ("+
			strings.Join(p.ignored, ", ")+"); move the models and what the queries use out of them")
	}
	return diag.New(pos, msg, "report this as a maago bug")
}

// caseHint is "did you mean Y? " for "undefined: X" when p declares a
// name Y that differs from X only in case, such as a name maago generates
// with an initialism in capitals (D-110), and "" otherwise. For pkg.X,
// go/types gives the hint itself.
func caseHint(p *pkg, msg string) string {
	name, ok := strings.CutPrefix(msg, "undefined: ")
	if !ok || p.types == nil {
		return ""
	}
	for _, n := range p.types.Scope().Names() {
		if n != name && strings.EqualFold(n, name) {
			return "did you mean " + n + "? "
		}
	}
	return ""
}

// importerFunc is a function as a types.Importer.
type importerFunc func(string) (*types.Package, error)

func (f importerFunc) Import(path string) (*types.Package, error) { return f(path) }

// goList runs go list in root and decodes the packages it prints.
func goList(root string, args ...string) ([]listed, []diag.Diagnostic) {
	cmd := exec.Command("go", append([]string{"list"}, args...)...)
	cmd.Dir = root
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if errors.Is(err, exec.ErrNotFound) {
		return nil, []diag.Diagnostic{diag.New(token.Position{}, "maago needs the go command to type-check the project, and cannot find it",
			"install Go, or put the go command on PATH")}
	}
	if err != nil {
		// All that go says, on one line, but the "go: downloading …" lines:
		// its last line alone may be only what to run ("go work use").
		var said []string
		for _, line := range strings.Split(stderr.String(), "\n") {
			if line = strings.TrimSpace(line); line != "" && !strings.HasPrefix(line, "go: downloading ") {
				said = append(said, line)
			}
		}
		if said == nil {
			said = []string{err.Error()}
		}
		line := said[0]
		for _, s := range said[1:] { // "to update it:" and what to run go together
			if strings.HasSuffix(line, ":") {
				line += " " + s
			} else {
				line += "; " + s
			}
		}
		return nil, []diag.Diagnostic{diag.New(token.Position{}, "go list failed: "+diag.OneLine(line),
			"do what go says above, then make sure go build works")}
	}
	var list []listed
	for dec := json.NewDecoder(bytes.NewReader(out)); dec.More(); {
		var l listed
		if err := dec.Decode(&l); err != nil {
			return nil, bug("cannot read the output of go list: " + err.Error())
		}
		list = append(list, l)
	}
	return list, nil
}

// bug is an error that only a bug of maago causes.
func bug(msg string) []diag.Diagnostic {
	return []diag.Diagnostic{diag.New(token.Position{}, diag.OneLine(msg), "report this as a maago bug")}
}
