// Package pipeline runs the stages of maago gen, writes what they generate,
// and compares it with what is on disk (D-60, D-61, D-67). A stage is a
// list of steps; checks and generators are both steps, and a generator is
// a step that fills Run.Files.
package pipeline

import (
	"bytes"
	"errors"
	"go/token"
	"io/fs"
	"maps"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"

	"github.com/maago-web/maago/internal/diag"
	"github.com/maago-web/maago/internal/project"
)

// Marker is the first line of every file maago generates. A file is
// maago's, to overwrite or remove, only if its first line is Marker (D-67).
const Marker = "// Code generated by maago. DO NOT EDIT."

// Run is what the steps share.
type Run struct {
	Root  string            // project root
	Files map[string][]byte // generated files, keyed by slash path relative to Root
}

// Step checks or generates part of the project.
type Step func(*Run) []diag.Diagnostic

// Gen runs the stages and, only if no step reported an error, writes what
// they generated. It returns the removed files.
func Gen(root string, stages [][]Step) (removed []string, ds []diag.Diagnostic) {
	r := &Run{Root: root, Files: map[string][]byte{}}
	if ds := Generate(r, stages); len(ds) > 0 {
		return nil, ds
	}
	return Write(root, r.Files)
}

// Generate runs the stages in order. Every step of a stage runs, so all of
// its independent errors are reported together; a stage with errors stops
// the run, so later stages cannot add errors that follow from them.
func Generate(r *Run, stages [][]Step) []diag.Diagnostic {
	for _, stage := range stages {
		var ds []diag.Diagnostic
		for _, step := range stage {
			ds = append(ds, step(r)...)
		}
		if len(ds) > 0 {
			return ds
		}
	}
	return nil
}

// Write makes the generated files under root equal to files: it writes
// them, then removes generated files that are not in files. Everything is
// checked before anything on disk changes. Files whose content is already
// on disk are skipped; the others are written to temporary files next to
// them and renamed into place only when all of those succeed. A failed
// rename or removal can leave the work half done, and running again
// finishes it. Write returns the removed files.
func Write(root string, files map[string][]byte) (removed []string, ds []diag.Diagnostic) {
	paths := slices.Sorted(maps.Keys(files))
	if ds := checkFiles(paths, files); len(ds) > 0 {
		return nil, ds
	}
	owned, ds := Owned(root)
	if len(ds) > 0 {
		return nil, ds
	}
	var todo []string
	for _, p := range paths {
		old, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p)))
		switch {
		case errors.Is(err, fs.ErrNotExist):
			todo = append(todo, p)
		case err != nil:
			ds = append(ds, diag.New(at(p), "cannot read file: "+diag.OneLine(err.Error()), "make sure the file can be read, then rerun maago gen"))
		case !isOwned(old):
			ds = append(ds, notGenerated(p))
		case !bytes.Equal(old, files[p]):
			todo = append(todo, p)
		}
	}
	if len(ds) > 0 {
		return nil, ds
	}

	type rename struct{ tmp, dst, path string }
	var renames []rename
	removeTemps := func(rs []rename) {
		for _, r := range rs {
			os.Remove(r.tmp)
		}
	}
	for _, p := range todo {
		dst := filepath.Join(root, filepath.FromSlash(p))
		tmp, err := writeTemp(dst, files[p])
		if err != nil {
			removeTemps(renames)
			return nil, []diag.Diagnostic{diag.New(at(p),
				"cannot write generated file: "+diag.OneLine(err.Error()), "make sure the directory can be written, then rerun maago gen")}
		}
		renames = append(renames, rename{tmp, dst, p})
	}
	for i, r := range renames {
		if err := os.Rename(r.tmp, r.dst); err != nil {
			removeTemps(renames[i:])
			return nil, []diag.Diagnostic{diag.New(at(r.path),
				"cannot replace generated file: "+diag.OneLine(err.Error()), "rerun maago gen; files already written are skipped")}
		}
	}
	for _, p := range owned {
		if _, ok := files[p]; ok {
			continue
		}
		if err := os.Remove(filepath.Join(root, filepath.FromSlash(p))); err != nil && !errors.Is(err, fs.ErrNotExist) {
			ds = append(ds, diag.New(at(p), "cannot remove old generated file: "+diag.OneLine(err.Error()), "remove it by hand, or rerun maago gen"))
			continue
		}
		removed = append(removed, p)
	}
	return removed, ds
}

// Check reports every difference between files and the generated files on
// disk: missing, out of date, or no longer generated. It writes nothing.
func Check(root string, files map[string][]byte) []diag.Diagnostic {
	paths := slices.Sorted(maps.Keys(files))
	if ds := checkFiles(paths, files); len(ds) > 0 {
		return ds
	}
	owned, ds := Owned(root)
	if len(ds) > 0 {
		return ds
	}
	for _, p := range paths {
		old, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p)))
		switch {
		case errors.Is(err, fs.ErrNotExist):
			ds = append(ds, diag.New(at(p), "generated file is missing", "run maago gen"))
		case err != nil:
			ds = append(ds, diag.New(at(p), "cannot read file: "+diag.OneLine(err.Error()), "make sure the file can be read"))
		case !isOwned(old):
			ds = append(ds, notGenerated(p))
		case !bytes.Equal(old, files[p]):
			ds = append(ds, diag.New(at(p), "generated file is out of date", "run maago gen; do not edit generated files by hand"))
		}
	}
	for _, p := range owned {
		if _, ok := files[p]; !ok {
			ds = append(ds, diag.New(at(p), "generated file is no longer generated", "run maago gen to remove it"))
		}
	}
	return ds
}

// Owned returns the slash paths, sorted, of the Go files under root that
// maago generated. It looks where project.GoFiles looks.
func Owned(root string) ([]string, []diag.Diagnostic) {
	files, ds := project.GoFiles(root)
	var owned []string
	for _, p := range files {
		b, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(p)))
		if err != nil {
			ds = append(ds, diag.New(at(p), "cannot read file: "+diag.OneLine(err.Error()), "make sure the file can be read"))
			continue
		}
		if isOwned(b) {
			owned = append(owned, p)
		}
	}
	return owned, ds
}

func isOwned(b []byte) bool {
	line, _, _ := bytes.Cut(b, []byte("\n"))
	return string(bytes.TrimSuffix(line, []byte("\r"))) == Marker
}

// checkFiles rejects what no generator should produce: a path that is not
// clean, local, and on one line, or content without the marker.
func checkFiles(paths []string, files map[string][]byte) []diag.Diagnostic {
	var ds []diag.Diagnostic
	for _, p := range paths {
		switch {
		case path.Clean(p) != p || !filepath.IsLocal(filepath.FromSlash(p)) || strings.ContainsAny(p, "\r\n"):
			ds = append(ds, diag.New(at(p), "generated file path is not a clean path inside the project", "this is a bug in maago; please report it"))
		case !isOwned(files[p]):
			ds = append(ds, diag.New(at(p), "generated content lacks the maago marker", "this is a bug in maago; please report it"))
		}
	}
	return ds
}

func notGenerated(p string) diag.Diagnostic {
	return diag.New(at(p), "file was not generated by maago, but maago generates a file at this path",
		"rename or move this file")
}

func at(p string) token.Position { return token.Position{Filename: p} }

// writeTemp writes b to a new temporary file in dst's directory, creating
// the directory if needed, and returns the temporary file's name.
func writeTemp(dst string, b []byte) (string, error) {
	dir := filepath.Dir(dst)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	f, err := os.CreateTemp(dir, ".maago-*.tmp")
	if err != nil {
		return "", err
	}
	_, err = f.Write(b)
	if err == nil {
		err = f.Chmod(0o644)
	}
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		os.Remove(f.Name())
		return "", err
	}
	return f.Name(), nil
}
