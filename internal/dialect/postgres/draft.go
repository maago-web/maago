package postgres

import (
	"fmt"
	"slices"
	"strings"

	"github.com/maago-web/maago/internal/dialect"
	"github.com/maago-web/maago/internal/migrate"
	"github.com/maago-web/maago/internal/model"
)

// Draft returns the SQL that turns the migrations into the models, for
// the changes cs that migrate.Diff found, in their order. What the models
// have is written from the models, as DDL writes it; the foreign keys of
// new tables come last, as in DDL, once every table exists.
func Draft(apps []*model.App, cs []migrate.Change) string {
	var stmts, fks []string
	for _, c := range cs {
		switch c.Kind {
		case migrate.CreateTable:
			m, refs := dialect.Model(apps, c.To.Name)
			stmts = append(stmts, table(m))
			stmts = append(stmts, indexStmts(m)...)
			fks = append(fks, foreignKeys(m, refs)...)
		default:
			stmts = append(stmts, statements(apps, c, cs)...)
		}
	}
	stmts = append(stmts, fks...)
	if len(stmts) == 0 {
		return ""
	}
	return strings.Join(stmts, "\n\n") + "\n"
}

// statements writes a change of a table on both sides, or a dropped one.
func statements(apps []*model.App, c migrate.Change, cs []migrate.Change) []string {
	alter := func(format string, args ...any) string {
		return fmt.Sprintf("ALTER TABLE %s ", dialect.Quote(c.Table())) + fmt.Sprintf(format, args...) + ";"
	}
	switch c.Kind {
	case migrate.DropTable:
		return []string{dialect.DropTable(c.From.Name)}
	case migrate.DropColumn:
		return []string{dialect.DropColumn(c.From.Name, c.Old.Name)}
	case migrate.DropFK:
		return []string{alter("DROP CONSTRAINT %s", dialect.Quote(c.FK.Name))}
	case migrate.DropCheck:
		return []string{alter("DROP CONSTRAINT %s", dialect.Quote(c.Check.Name))}
	case migrate.DropIndex:
		if c.Index.Constraint {
			return []string{alter("DROP CONSTRAINT %s", dialect.Quote(c.Index.Name))}
		}
		return []string{fmt.Sprintf("DROP INDEX %s;", dialect.Quote(c.Index.Name))}
	case migrate.AddColumn:
		f := dialect.Field(apps, c.To.Name, c.New.Name)
		warn := ""
		if !f.Pointer && f.Default == nil {
			warn = dialect.NoDefault(c.To.Name, f.Column)
		}
		return []string{warn + alter("ADD COLUMN %s", column(f))}
	case migrate.AddCheck:
		if added(cs, c, migrate.AddColumn, c.Check.Column) {
			return nil // written with its column
		}
		e := check(dialect.Field(apps, c.To.Name, c.Check.Column))
		if e == "" {
			panic("postgres.Draft: the models have no check on " + c.Check.Column)
		}
		return []string{alter("ADD CONSTRAINT %s CHECK (%s)", dialect.Quote(c.Check.Name), e)}
	case migrate.AlterType:
		// A default that does not cast to the new type makes TYPE fail,
		// so it goes first and comes back after. USING casts to the type
		// without its length: a cast to VARCHAR(100) cuts longer values,
		// while assigning to it refuses them.
		f := dialect.Field(apps, c.To.Name, c.New.Name)
		col := dialect.Quote(f.Column)
		var s []string
		if c.Old.Default != "" {
			s = append(s, alter("ALTER COLUMN %s DROP DEFAULT", col))
		}
		s = append(s, alter("ALTER COLUMN %s TYPE %s USING %s::%s", col, typ(f), col, types[f.Type]))
		if c.Old.Default != "" && f.Default != nil {
			s = append(s, alter("ALTER COLUMN %s SET DEFAULT %s", col, literal(f.Type, *f.Default)))
		}
		return s
	case migrate.AlterNotNull:
		if c.New.NotNull {
			return []string{alter("ALTER COLUMN %s SET NOT NULL", dialect.Quote(c.New.Name))}
		}
		return []string{alter("ALTER COLUMN %s DROP NOT NULL", dialect.Quote(c.New.Name))}
	case migrate.AlterDefault:
		if c.Old.Default != "" && added(cs, c, migrate.AlterType, c.New.Name) {
			return nil // written with the type
		}
		f := dialect.Field(apps, c.To.Name, c.New.Name)
		if f.Default == nil {
			return []string{alter("ALTER COLUMN %s DROP DEFAULT", dialect.Quote(f.Column))}
		}
		return []string{alter("ALTER COLUMN %s SET DEFAULT %s", dialect.Quote(f.Column), literal(f.Type, *f.Default))}
	case migrate.DropPK:
		if slices.Equal(c.From.PK, c.To.PK) {
			return nil // only the identity differs: see AddPK
		}
		var s []string
		if c.From.PKAuto != "" {
			s = append(s, alter("ALTER COLUMN %s DROP IDENTITY", dialect.Quote(c.From.PK[0])))
		}
		return append(s, alter("DROP CONSTRAINT %s", dialect.Quote(c.From.PKName)))
	case migrate.AddPK:
		// The models' key is always id, generated BY DEFAULT.
		col := dialect.Quote(c.To.PK[0])
		identity := alter("ALTER COLUMN %s ADD GENERATED %s AS IDENTITY", col, c.To.PKAuto)
		if slices.Equal(c.From.PK, c.To.PK) {
			// The key stays, so no unchanged foreign key has to let go of it.
			if c.From.PKAuto != "" {
				identity = alter("ALTER COLUMN %s SET GENERATED %s", col, c.To.PKAuto)
			}
			return []string{identity}
		}
		return []string{alter("ADD CONSTRAINT %s PRIMARY KEY (%s)", dialect.Quote(c.To.PKName), dialect.QuoteAll(c.To.PK)), identity}
	case migrate.AddIndex:
		if c.Index.Constraint {
			return []string{alter("ADD CONSTRAINT %s UNIQUE (%s)", dialect.Quote(c.Index.Name), dialect.QuoteAll(c.Index.Columns))}
		}
		return []string{dialect.CreateIndex(c.To.Name, c.Index)}
	case migrate.AddFK:
		// The models' foreign keys are all ON UPDATE NO ACTION.
		return []string{alter("ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE %s", dialect.Quote(c.FK.Name),
			dialect.QuoteAll(c.FK.Columns), dialect.Quote(c.FK.RefTable), dialect.QuoteAll(c.FK.RefColumns), c.FK.OnDelete)}
	}
	panic(fmt.Sprintf("postgres.Draft: unexpected change kind %d", c.Kind))
}

// added reports whether cs has a change of kind on column of c's table.
func added(cs []migrate.Change, c migrate.Change, kind migrate.Kind, column string) bool {
	return slices.ContainsFunc(cs, func(o migrate.Change) bool {
		return o.Kind == kind && o.To == c.To && o.New.Name == column
	})
}
