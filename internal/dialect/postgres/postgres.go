// Package postgres writes PostgreSQL DDL for checked models (D-77,
// D-84..D-86).
package postgres

import (
	"fmt"
	"go/token"
	"strings"

	"github.com/maago-web/maago/internal/diag"
	"github.com/maago-web/maago/internal/dialect"
	"github.com/maago-web/maago/internal/model"
)

// maxName is PostgreSQL's identifier limit in bytes; longer names are
// silently cut, so they are refused instead.
const maxName = 63

var types = map[model.Type]string{
	model.Int64: "BIGINT", model.Int32: "INTEGER", model.Bool: "BOOLEAN", model.Float64: "DOUBLE PRECISION",
	model.String: "TEXT", model.Time: "TIMESTAMPTZ", model.Bytes: "BYTEA",
}

// DDL returns every CREATE TABLE, then every foreign key, then every
// index. PostgreSQL cannot refer to a table not yet created, so foreign
// keys come after all tables; that also covers models that refer to each
// other. Within each part, statements keep the order of the models.
func DDL(fset *token.FileSet, apps []*model.App) (string, []diag.Diagnostic) {
	ds := dialect.CheckNames(fset, apps, maxName)
	ds = append(ds, checkRelations(fset, apps)...)
	if len(ds) > 0 {
		return "", ds
	}
	var tables, fks, indexes []string
	for _, app := range apps {
		refs := dialect.Tables(app)
		for _, m := range app.Models {
			tables = append(tables, table(m))
			fks = append(fks, foreignKeys(m, refs)...)
			indexes = append(indexes, indexStmts(m)...)
		}
	}
	return strings.Join(append(append(tables, fks...), indexes...), "\n\n") + "\n", nil
}

func foreignKeys(m *model.Model, refs map[string]string) []string {
	var stmts []string
	for _, f := range m.Fields {
		if f.FK != "" {
			stmts = append(stmts, fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE NO ACTION;",
				dialect.Quote(m.Table), dialect.Quote(dialect.ForeignKeyName(m.Table, f.Column)), dialect.Quote(f.Column), dialect.Quote(refs[f.FK]), dialect.Quote("id")))
		}
	}
	return stmts
}

func indexStmts(m *model.Model) []string {
	var stmts []string
	for _, cols := range m.Indexes {
		stmts = append(stmts, fmt.Sprintf("CREATE INDEX %s ON %s (%s);",
			dialect.Quote(dialect.IndexName(m.Table, cols)), dialect.Quote(m.Table), dialect.QuoteAll(cols)))
	}
	return stmts
}

// checkRelations reports table and column names over the limit, and table
// or primary key names that clash with another relation: tables and the
// indexes behind primary keys, uniques and indexes share one namespace.
func checkRelations(fset *token.FileSet, apps []*model.App) []diag.Diagnostic {
	var ds []diag.Diagnostic
	taken := map[string]bool{}
	for _, app := range apps {
		for _, m := range app.Models {
			for _, cols := range m.Uniques {
				taken[dialect.UniqueName(m.Table, cols)] = true
			}
			for _, cols := range m.Indexes {
				taken[dialect.IndexName(m.Table, cols)] = true
			}
		}
	}
	for _, app := range apps {
		for _, m := range app.Models {
			pos := fset.Position(m.Pos)
			for _, n := range []string{m.Table, m.Table + "_pkey"} {
				if len(n) > maxName {
					ds = append(ds, diag.New(pos, fmt.Sprintf("name %q of %s is longer than %d bytes", n, m.Name, maxName), "shorten the table name with table=…"))
				}
				if taken[n] {
					ds = append(ds, diag.New(pos, fmt.Sprintf("name %q of %s is also the name of another table or index", n, m.Name), "rename the table with table=…"))
				}
				taken[n] = true
			}
			for _, f := range m.Fields {
				if len(f.Column) > maxName {
					ds = append(ds, diag.New(fset.Position(f.Pos), fmt.Sprintf("column %q of %s.%s is longer than %d bytes", f.Column, m.Name, f.Name, maxName), "shorten the field name"))
				}
			}
		}
	}
	return ds
}

func table(m *model.Model) string {
	var lines []string
	for _, f := range m.Fields {
		lines = append(lines, column(f))
	}
	for _, cols := range m.Uniques {
		lines = append(lines, fmt.Sprintf("CONSTRAINT %s UNIQUE (%s)", dialect.Quote(dialect.UniqueName(m.Table, cols)), dialect.QuoteAll(cols)))
	}
	return fmt.Sprintf("CREATE TABLE %s (\n    %s\n);", dialect.Quote(m.Table), strings.Join(lines, ",\n    "))
}

func column(f *model.Field) string {
	c := dialect.Quote(f.Column)
	if f.Name == "ID" {
		// BY DEFAULT accepts an explicit id, which does not advance the
		// sequence; generated code never supplies one.
		return c + " BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
	}
	s := c + " " + typ(f)
	if !f.Pointer {
		s += " NOT NULL"
	}
	if f.Default != nil {
		s += " DEFAULT " + literal(f.Type, *f.Default)
	}
	if e := check(f); e != "" {
		s += " CHECK (" + e + ")"
	}
	return s
}

func typ(f *model.Field) string {
	if f.Max > 0 {
		return fmt.Sprintf("VARCHAR(%d)", f.Max) // characters, like SQLite's length()
	}
	return types[f.Type]
}

// check is the expression of the one CHECK a field can have, or "".
func check(f *model.Field) string {
	if len(f.Choices) == 0 {
		return ""
	}
	quoted := make([]string, len(f.Choices))
	for i, v := range f.Choices {
		quoted[i] = dialect.String(v)
	}
	return fmt.Sprintf("%s IN (%s)", dialect.Quote(f.Column), strings.Join(quoted, ", "))
}

func literal(t model.Type, v string) string {
	switch t {
	case model.String:
		return dialect.String(v)
	case model.Bool:
		return v // true or false
	}
	return dialect.Number(t, v)
}
