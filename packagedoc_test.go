package maago_test

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"maps"
	"path/filepath"
	"slices"
	"strings"
	"testing"

	"github.com/maago-web/maago/internal/golden"
	"github.com/maago-web/maago/internal/ref"
)

// The package doc is the topics of maago doc: each one's summary, its
// closed lists, and the names of this package it explains. Every exported
// name is some topic's, once, so a name only generated code calls, which
// belongs in rt, has no place here (D-152). go test -update writes doc.go.
func TestPackageDoc(t *testing.T) {
	owner := map[string]string{}
	for _, topic := range ref.Topics {
		for _, name := range topic.API {
			if other, ok := owner[name]; ok {
				t.Errorf("%s is in the API of both %s and %s", name, other, topic.Name)
			}
			owner[name] = topic.Name
		}
	}
	exported := exports(t)
	for _, name := range exported {
		if owner[name] == "" {
			t.Errorf("%s is no topic's: add it to the API of the topic that explains it, or move it to rt if only generated code calls it", name)
		}
	}
	for _, name := range slices.Sorted(maps.Keys(owner)) {
		if !slices.Contains(exported, name) {
			t.Errorf("the API of %s names %s, which package maago does not export", owner[name], name)
		}
	}
	golden.Check(t, "doc.go", []byte(packageDoc()))
}

// exports are the exported names declared at the top of package maago's
// files: funcs, types, vars and consts, not methods.
func exports(t *testing.T) []string {
	t.Helper()
	paths, err := filepath.Glob("*.go")
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	fset := token.NewFileSet()
	for _, p := range paths {
		if strings.HasSuffix(p, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, p, nil, parser.SkipObjectResolution)
		if err != nil {
			t.Fatal(err)
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil && d.Name.IsExported() {
					names = append(names, d.Name.Name)
				}
			case *ast.GenDecl:
				for _, s := range d.Specs {
					switch s := s.(type) {
					case *ast.TypeSpec:
						if s.Name.IsExported() {
							names = append(names, s.Name.Name)
						}
					case *ast.ValueSpec:
						for _, n := range s.Names {
							if n.IsExported() {
								names = append(names, n.Name)
							}
						}
					}
				}
			}
		}
	}
	return names
}

// packageDoc is doc.go: a section for each topic, in go doc's syntax.
func packageDoc() string {
	var b strings.Builder
	line := func(s string) {
		if s == "" {
			b.WriteString("//\n")
		} else {
			b.WriteString("// " + s + "\n")
		}
	}
	text := func(s string) {
		for l := range strings.Lines(s) {
			line(strings.TrimRight(l, "\n"))
		}
	}
	b.WriteString("// Code generated by TestPackageDoc from the topics of maago doc. DO NOT EDIT.\n\n")
	text(`Package maago is what the code of a Maago project calls. maago gen writes
the rest from the project's models, queries, views and forms, and checks
what it cannot write. Each section below is a topic of maago doc: maago doc
TOPIC prints it in full, with a complete example that maago's tests run.
The code maago gen writes calls package rt, which is not for apps.`)
	for _, topic := range ref.Topics {
		line("")
		line("# " + topic.Title)
		line("")
		text(topic.Summary)
		for _, l := range topic.Lists {
			line("")
			line(l.Name + ":")
			line("")
			for _, it := range l.Items {
				s := it.Name + ": " + it.Text
				if len(it.Values) > 0 {
					s += " Values: " + strings.Join(it.Values, ", ") + "."
				}
				line("  - " + s) // go doc wraps it
			}
		}
		if len(topic.API) > 0 {
			var links []string
			for _, name := range topic.API {
				links = append(links, "["+name+"]")
			}
			line("")
			line("Names: " + strings.Join(links, ", ") + ".")
		}
		line("")
		line(fmt.Sprintf("maago doc %s has the full text and an example.", topic.Name))
	}
	b.WriteString("package maago\n")
	return b.String()
}
