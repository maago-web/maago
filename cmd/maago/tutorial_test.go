const steps = "../../examples/board/steps"

// The board tutorial walks from its first step to its last as each step
// expects (D-103). The stylesheet the last step holds is what maago
// tailwind makes of it: a step that changed the classes and not the CSS
// fails, when the standalone build is there (D-138).
func TestBoardTutorial(t *testing.T) {
	root, err := walk(t, steps)
	if err != nil {
		t.Fatal(err)
	}
	b, ok := tailwindBuilds[tailwindPlatform()]
	cache, _ := os.UserCacheDir()
	if _, err := os.Stat(filepath.Join(cache, "maago", "tailwindcss-"+tailwindVersion+"-"+b.asset)); !ok || err != nil && os.Getenv("CI") == "" {
		t.Skip("tailwindcss " + tailwindVersion + " is not in the cache: the stylesheet is not compared; run maago tailwind once, or set CI")
	}
	css := filepath.Join(root, "board", "static", "tailwind.css")
	committed := readFile(t, css)
	t.Chdir(root)
	if code, stdout, stderr := runCmd("tailwind"); code != 0 {
		t.Fatalf("maago tailwind: %s%s", stdout, stderr)
	}
	if readFile(t, css) != committed {
		t.Error("board/static/tailwind.css is not what maago tailwind makes of the last step: run it, and commit the CSS in the step that changed the classes")
	}
}

// The walk stops at a step that goes wrong, whichever part of it does:
// the queries, the expected error, or the app's tests.
func TestBoardTutorialCatches(t *testing.T) {
	for _, c := range []struct{ name, patch, old, new, by string }{
		{"query", "0005-Add-post-queries.patch", "p.body, p.status", "p.nope, p.status", "maago gen:\n"},
		{"expected error", "0006-Try-a-model-result-that-misses-a-column.patch", "title, status", "title, body, status", "maago gen: expected\n"},
		{"app test", "0005-Add-post-queries.patch", `{0, "[글 5 글 4]"}`, `{0, "[글 4 글 5]"}`, "go test: "},
		// The expected error is the whole first line, not a prefix of it.
		{"short expectation", "0006-Try-a-model-result-that-misses-a-column.patch",
			`Maago-Expect: board/queries/recent_posts.sql:4:1: result columns do not match model Post: missing "body"`,
			`Maago-Expect: board/queries/recent_posts.sql:4:1: result columns do not match model Post`, "maago gen: expected\n"},
		// Both template errors at once (D-61): expecting one is not enough.
		{"one template error of two", "0009-Try-two-typos-in-the-templates.patch",
			"\nMaago-Expect: board/templates/post_page.html:3:13: PostPage.Post has no field or method \"Titel\"", "", "maago gen: expected\n"},
		// A migration the practice database refuses stops the walk, after the
		// move to PostgreSQL too (D-141).
		{"a SQLite migration on PostgreSQL", "0013-Move-to-PostgreSQL.patch", `+    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,`, `+    "id" INTEGER PRIMARY KEY AUTOINCREMENT,`, "maago gen:\n"},
		{"gofmt", "0002-Add-Board-Post-and-Comment.patch", "+\tdb := maagotest.DB(t)", "+    db := maagotest.DB(t)", "gofmt -l: "},
		// What maago add writes comes from the trailer, not the patch.
		{"no maago add", "0020-Add-accounts.patch", "\nMaago-Run: maago add auth", "", "maago gen: expected\n"},
		{"an unknown trailer", "0020-Add-accounts.patch", "Maago-Run: maago add auth", "Maago-Run: maago add auth now", "unknown trailer "},
		{"author check", "0022-Posts-have-authors.patch", "+\tif u.IsStaff || p.AuthorID != nil && *p.AuthorID == u.ID {", "+\tif u.IsStaff || true {", "go test: "},
		{"admin columns", "0025-Board-in-the-admin.patch", ",admin_list=(Title,BoardID,Status,AuthorID,CreatedAt)", "", "go test: "},
		// Who gets a draft's file is the view's to check (D-140).
		{"a draft's file", "0029-Attach-files-to-posts.patch", "+\tif post.Status == \"draft\" {", "+\tif false {", "go test: "},
		{"me without a sign-in", "0030-Me.patch", `+	maago.GET("/me", "me", Me, maago.LoginRequired),`, `+	maago.GET("/me", "me", Me),`, "go test: "},
		{"anybody edits", "0031-Edit-a-post.patch", "+\tif err := mayChange(ctx, p); err != nil {", "+\tif err := error(nil); err != nil {", "go test: "},
	} {
		t.Run(c.name, func(t *testing.T) {
			dir := t.TempDir()
			if err := os.CopyFS(dir, os.DirFS(steps)); err != nil {
				t.Fatal(err)
			}
			p := filepath.Join(dir, c.patch)
			src := readFile(t, p)
			if !strings.Contains(src, c.old) {
				t.Fatalf("%s has no %q", c.patch, c.old)
			}
			writeFile(t, p, strings.Replace(src, c.old, c.new, 1))
			if _, err := walk(t, dir); err == nil || !strings.HasPrefix(err.Error(), c.patch+": "+c.by) {
				t.Errorf("walk: %v", err)
			}
		})
	}
}

// The walk reads a step's trailers before it applies the step: a database
// it does not know, and a second move, are errors, and without a server CI
// fails at the move, where a local run skips (D-91). In CI, so that none
// of these skips.
func TestBoardTutorialPostgresTrailer(t *testing.T) {
	t.Setenv("CI", "true")
	t.Setenv("MAAGO_TEST_PG_URL", "")
	for _, c := range []struct{ name, trailers, want string }{
		{"unknown database", "Maago-Database: mysql", `unknown trailer "Maago-Database: mysql"`},
		{"twice", "Maago-Database: postgres\nMaago-Database: postgres", "Maago-Database: postgres twice"},
		{"no server in CI", "Maago-Database: postgres", "MAAGO_TEST_PG_URL is not set; CI must run the PostgreSQL tests"},
	} {
		t.Run(c.name, func(t *testing.T) {
			t.Cleanup(func() {
				if t.Skipped() {
					t.Error("skipped: the walk got past the trailer")
				}
			})
			dir := t.TempDir()
			p := filepath.Join(dir, "0001-Start-the-project.patch")
			src := readFile(t, filepath.Join(steps, filepath.Base(p)))
			if !strings.Contains(src, "앱이 import한다.\n") {
				t.Fatal("0001's message has changed: put the trailer elsewhere")
			}
			writeFile(t, p, strings.Replace(src, "앱이 import한다.\n", "앱이 import한다.\n\n"+c.trailers+"\n", 1))
			if _, err := walk(t, dir); err == nil || !strings.HasPrefix(err.Error(), "0001-Start-the-project.patch: "+c.want) {
				t.Errorf("walk: %v", err)
			}
		})
	}
}

// walk applies the patches in dir one by one to a new project, as a reader
// of the tutorial would make them, and checks each step. A step whose
// commit message has Maago-Expect: lines must fail maago gen with exactly
// those diagnostics; any other step must pass gen, check and migrate, and
// the app's tests. The steps share the database maago migrate makes, as a
// reader's would; the app's tests get their own from maagotest (D-113).
// From the step whose message has Maago-Database: postgres, that database
// is a schema of MAAGO_TEST_PG_URL's server, made for the walk (D-141).
func walk(t *testing.T, dir string) (root string, err error) {
	t.Helper()
	noEnv(t) // maago reads .env, as for the reader
	patches, _ := filepath.Glob(filepath.Join(dir, "*.patch"))
	if len(patches) == 0 {
		return "", fmt.Errorf("no patches in %s", dir)
	}
	// The go command compares go.work's directory with the real path.
	root, err = filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		return "", err
	}
	repo, err := filepath.EvalSymlinks("../..")
	if err != nil {
		return "", err
	}
	if repo, err = filepath.Abs(repo); err != nil {
		return "", err
	}
	// A repository of its own, so git apply works on root and nowhere else.
	if out, err := osexec.Command("git", "init", "-q", root).CombinedOutput(); err != nil {
		return "", fmt.Errorf("git init: %v\n%s", err, out)
	}
	writeFile(t, filepath.Join(root, "go.work"), "go 1.25.0\n\nuse .\n\nreplace github.com/maago-web/maago => "+repo+"\n")
	writeFile(t, filepath.Join(root, ".env"), "MAAGO_DATABASE_URL=sqlite:board.db\n")
	schema := "" // the walk's PostgreSQL schema, once a step moved to it
	for _, p := range patches {
		src, err := os.ReadFile(p)
		if err != nil {
			return "", err
		}
		tr, err := expected(src)
		if err == nil && tr.postgres > 0 {
			schema, err = toPostgres(t, root, schema, tr.postgres)
		}
		if err == nil {
			err = walkStep(root, p, tr)
		}
		if err != nil {
			return "", fmt.Errorf("%s: %w", filepath.Base(p), err)
		}
	}
	// The last main makes the first staff account (D-130) on the steps'
	// database, as its reader would.
	run := goCmd(root, "run", ".", "-createsuperuser")
	run.Env = append(run.Env, "MAAGO_SUPERUSER_EMAIL=boss@example.com", "MAAGO_SUPERUSER_PASSWORD=correct horse battery staple")
	if out, err := run.CombinedOutput(); err != nil || !strings.Contains(string(out), "created boss@example.com") {
		return "", fmt.Errorf("go run . -createsuperuser: %v\n%s", err, out)
	}
	if schema != "" { // .env's search_path reached the command
		var n int
		if err := withPostgres(func(db *sql.DB) error {
			return db.QueryRow("SELECT count(*) FROM " + schema + ".auth_user WHERE email = 'boss@example.com'").Scan(&n)
		}); err != nil || n != 1 {
			return "", fmt.Errorf("the superuser is not in schema %s: %v", schema, err)
		}
	}
	return root, nil
}

// toPostgres moves the walk at root to a new schema of MAAGO_TEST_PG_URL's
// server, as a reader moves to PostgreSQL by .env: once, and without a
// server, a skip, or a failure in CI (D-91).
func toPostgres(t *testing.T, root, schema string, n int) (string, error) {
	if schema != "" || n > 1 {
		return "", fmt.Errorf("Maago-Database: postgres twice")
	}
	server := os.Getenv("MAAGO_TEST_PG_URL")
	switch {
	case server != "":
	case os.Getenv("CI") != "":
		return "", fmt.Errorf("MAAGO_TEST_PG_URL is not set; CI must run the PostgreSQL tests")
	default:
		t.Skip("MAAGO_TEST_PG_URL is not set; set it to a PostgreSQL server to run this test")
	}
	// Named by the test, so the next run drops what a killed one left.
	schema = maagotest.SchemaName("github.com/maago-web/maago/cmd/maago board walk", t.Name(), 0)
	if err := withPostgres(func(db *sql.DB) error {
		_, err := db.Exec("DROP SCHEMA IF EXISTS " + schema + " CASCADE; CREATE SCHEMA " + schema)
		return err
	}); err != nil {
		return "", err
	}
	t.Cleanup(func() {
		if err := withPostgres(func(db *sql.DB) error {
			_, err := db.Exec("SET lock_timeout = '5s'; DROP SCHEMA IF EXISTS " + schema + " CASCADE")
			return err
		}); err != nil {
			t.Errorf("cannot drop schema %s: %v", schema, err)
		}
	})
	u, err := url.Parse(server)
	if err != nil {
		return "", fmt.Errorf("MAAGO_TEST_PG_URL does not parse")
	}
	q := u.Query()
	q.Set("search_path", schema)
	u.RawQuery = q.Encode()
	writeFile(t, filepath.Join(root, ".env"), "MAAGO_DATABASE_URL="+u.String()+"\n")
	return schema, nil
}

// withPostgres runs f on MAAGO_TEST_PG_URL's server.
func withPostgres(f func(*sql.DB) error) error {
	db, err := sql.Open("pgx", os.Getenv("MAAGO_TEST_PG_URL"))
	if err != nil {
		return err
	}
	defer db.Close()
	return f(db)
}

// goCmd is the go command in root, offline, on root's go.work.
func goCmd(root string, args ...string) *osexec.Cmd {
	cmd := osexec.Command("go", args...)
	cmd.Dir = root
	cmd.Env = append(os.Environ(),
		// These win over the environment's own: exec.Cmd uses the last
		// value of a key.
		"GOWORK="+filepath.Join(root, "go.work"),
		"GOPROXY=off",           // the module cache only: cmd/maago's tests fetched the same versions
		"GOFLAGS=-mod=readonly", // a stale go.sum fails, whatever GOFLAGS says
	)
	return cmd
}

func walkStep(root, patch string, tr trailers) error {
	want := tr.want
	// What maago add writes is not in the patch, as generated files are
	// not: the step runs it first, as its reader did.
	for _, app := range tr.apps {
		if _, ds := scaffold.Add(root, app); ds != nil {
			return fmt.Errorf("maago add %s:\n%s", app, text(ds))
		}
	}
	abs, _ := filepath.Abs(patch)
	apply := osexec.Command("git", "apply", abs)
	apply.Dir = root
	if out, err := apply.CombinedOutput(); err != nil {
		return fmt.Errorf("git apply: %v\n%s", err, out)
	}

	_, ds := build.Gen(root)
	got := diagnostics(text(ds))
	if want != nil {
		if !slices.Equal(slices.Sorted(slices.Values(got)), slices.Sorted(slices.Values(want))) {
			return fmt.Errorf("maago gen: expected\n%s\ngot\n%s", strings.Join(want, "\n"), text(ds))
		}
		return nil
	}
	if ds != nil {
		return fmt.Errorf("maago gen:\n%s", text(ds))
	}
	if out, err := osexec.Command("gofmt", "-l", root).CombinedOutput(); err != nil || len(out) > 0 {
		return fmt.Errorf("gofmt -l: %v\n%s", err, out)
	}
	if ds := build.Check(root); ds != nil {
		return fmt.Errorf("maago check:\n%s", text(ds))
	}
	if _, ds := build.Migrate(root); ds != nil {
		return fmt.Errorf("maago migrate:\n%s", text(ds))
	}
	// The app's tests find the root's .env from their package's directory,
	// as a reader's do (D-113): no address is given them.
	if out, err := goCmd(root, "test", "./...").CombinedOutput(); err != nil {
		return fmt.Errorf("go test: %v\n%s", err, out)
	}
	return nil
}

// trailers are what a step's commit message asks of the walk.
type trailers struct {
	want, apps []string // Maago-Expect:, Maago-Run: maago add
	postgres   int      // Maago-Database: postgres lines
}

// expected reads the trailers of a patch's commit message, which ends
// where the diff starts (steps.sh packs without a diffstat): the
// Maago-Expect: lines, the apps of Maago-Run: maago add APP lines, which
// the step runs before its patch, and Maago-Database: postgres, which moves
// the walk to PostgreSQL before it. The mail header before it has no
// Maago- lines.
func expected(patch []byte) (tr trailers, err error) {
	msg, _, ok := strings.Cut(string(patch), "\ndiff --git ")
	if !ok {
		return tr, fmt.Errorf("no diff after the commit message")
	}
	for _, line := range strings.Split(msg, "\n") {
		switch {
		case strings.HasPrefix(line, "Maago-Expect: "):
			tr.want = append(tr.want, strings.TrimPrefix(line, "Maago-Expect: "))
		case strings.HasPrefix(line, "Maago-Run: maago add ") && !strings.ContainsAny(strings.TrimPrefix(line, "Maago-Run: maago add "), " \t") && line != "Maago-Run: maago add ":
			tr.apps = append(tr.apps, strings.TrimPrefix(line, "Maago-Run: maago add "))
		case line == "Maago-Database: postgres":
			tr.postgres++
		case strings.HasPrefix(line, "Maago-"):
			return tr, fmt.Errorf("unknown trailer %q; maago knows Maago-Expect:, Maago-Run: maago add APP and Maago-Database: postgres", line)
		}
	}
	return tr, nil
}
