// walk applies the patches in dir one by one to a new project, as a reader
// of the tutorial would make them, and checks each step. A step whose
// commit message has Maago-Expect: lines must fail maago gen with exactly
// those diagnostics; any other step must pass gen, check and migrate, and
// the app's tests. The steps share the database maago migrate makes, as a
// reader's would; the app's tests get their own from maagotest (D-113).
// From the step whose message has Maago-Database: postgres, that database
// is a schema of MAAGO_TEST_PG_URL's server, made for the walk (D-141).
func walk(t *testing.T, dir string) (root string, err error) {
	t.Helper()
	patches, _ := filepath.Glob(filepath.Join(dir, "*.patch"))
	if len(patches) == 0 {
		return "", fmt.Errorf("no patches in %s", dir)
	}
	w, err := newWalker(t)
	if err != nil {
		return "", err
	}
	for _, p := range patches {
		if err := w.step(t, p); err != nil {
			return "", err
		}
	}
	if err := w.ship(t, filepath.Base(patches[len(patches)-1])); err != nil {
		return "", err
	}
	return w.root, nil
}

// A walker is a walk's project, and its PostgreSQL schema once a step
// moved to it.
type walker struct{ root, schema string }

// newWalker makes the project a walk starts from.
func newWalker(t *testing.T) (*walker, error) {
	noEnv(t) // maago reads .env, as for the reader
	// The go command compares go.work's directory with the real path.
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		return nil, err
	}
	repo, err := filepath.EvalSymlinks("../..")
	if err != nil {
		return nil, err
	}
	if repo, err = filepath.Abs(repo); err != nil {
		return nil, err
	}
	// A repository of its own, so git apply works on root and nowhere else.
	if out, err := osexec.Command("git", "init", "-q", root).CombinedOutput(); err != nil {
		return nil, fmt.Errorf("git init: %v\n%s", err, out)
	}
	writeFile(t, filepath.Join(root, "go.work"), "go 1.25.0\n\nuse .\n\nreplace github.com/maago-web/maago => "+repo+"\n")
	writeFile(t, filepath.Join(root, ".env"), "MAAGO_DATABASE_URL=sqlite:board.db\n")
	return &walker{root: root}, nil
}

// step walks the step of patch p; its error names the patch.
func (w *walker) step(t *testing.T, p string) error {
	src, err := os.ReadFile(p)
	if err != nil {
		return err
	}
	tr, err := expected(src)
	if err == nil && tr.postgres > 0 {
		w.schema, err = toPostgres(t, w.root, w.schema, tr.postgres)
	}
	if err == nil {
		err = walkStep(w.root, p, tr)
	}
	if err != nil {
		return fmt.Errorf("%s: %w", filepath.Base(p), err)
	}
	return nil
}

// ship ships the walk's last step, last: what goes wrong past the steps
// is the last one's, its main.
func (w *walker) ship(t *testing.T, last string) error {
	if err := ship(t, w.root, w.schema); err != nil {
		return fmt.Errorf("%s: %w", last, err)
	}
	return nil
}

// clone copies the walk to a project of t's: its files, and on PostgreSQL
// an empty schema of t's own, which the row's step migrates. t is the
// test the copy is for: the schema is named by it.
func (w *walker) clone(t *testing.T) (*walker, error) {
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		return nil, err
	}
	if err := os.CopyFS(root, os.DirFS(w.root)); err != nil {
		return nil, err
	}
	c := &walker{root: root}
	if w.schema != "" {
		if c.schema, err = toPostgres(t, root, "", 1); err != nil {
			return nil, err
		}
	}
	return c, nil
}

// ship does with the last step what its reader does to ship it (D-142):
// it builds the binary as a container does, without cgo for Linux, then
// builds one for this machine, which migrates the steps' database, emptied
// first, as it starts (D-153), makes the first staff account (D-130), and
// serves the board on PORT until SIGTERM stops it cleanly. Given a bucket
// with no address, it stops as it starts. On PostgreSQL, a job written to
// the outbox reaches the webhook of the environment: main runs the worker
// (D-159). It keeps the files in the bucket of the environment, an S3 of
// the test's: the worker writes a board's export there, the sweep deletes
// a file two days old that no row keeps, and a job of a kind main does
// not know stays, with its error (D-160, D-161).
func ship(t *testing.T, root, schema string) error {
	cross := goCmd(root, "build", "-o", filepath.Join(t.TempDir(), "board"), ".")
	cross.Env = append(cross.Env, "CGO_ENABLED=0", "GOOS=linux", "GOARCH=amd64")
	if out, err := cross.CombinedOutput(); err != nil {
		return fmt.Errorf("CGO_ENABLED=0 GOOS=linux go build: %v\n%s", err, out)
	}
	bin := filepath.Join(t.TempDir(), "board")
	if out, err := goCmd(root, "build", "-o", bin, ".").CombinedOutput(); err != nil {
		return fmt.Errorf("go build: %v\n%s", err, out)
	}
	// On an empty database: the binary migrates it as it starts (D-153).
	if schema != "" {
		if err := withPostgres(func(db *sql.DB) error {
			_, err := db.Exec("DROP SCHEMA " + schema + " CASCADE; CREATE SCHEMA " + schema)
			return err
		}); err != nil {
			return err
		}
	}
	su := osexec.Command(bin, "-createsuperuser")
	su.Dir = root
	su.Env = append(os.Environ(), "MAAGO_SUPERUSER_EMAIL=boss@example.com", "MAAGO_SUPERUSER_PASSWORD=correct horse battery staple")
	if out, err := su.CombinedOutput(); err != nil || !strings.Contains(string(out), "created boss@example.com") {
		return fmt.Errorf("board -createsuperuser: %v\n%s", err, out)
	}
	if schema != "" { // .env's search_path reached the binary
		var n int
		if err := withPostgres(func(db *sql.DB) error {
			return db.QueryRow("SELECT count(*) FROM " + schema + ".auth_user WHERE email = 'boss@example.com'").Scan(&n)
		}); err != nil || n != 1 {
			return fmt.Errorf("the superuser is not in schema %s: %v", schema, err)
		}
	}
	env := []string{"BOARD_SITE_URL=http://localhost:8000"}
	if err := refuse(root, bin, append(env, "BOARD_S3_BUCKET=media"), "s3: Store.Endpoint is empty"); err != nil {
		return fmt.Errorf("board with BOARD_S3_BUCKET alone: %v", err)
	}
	var use func(string) error
	if schema != "" { // jobs in the outbox: main's worker sends one to the webhook, writes the other's files
		var board int64
		if err := withPostgres(func(db *sql.DB) error {
			if err := db.QueryRow("INSERT INTO " + schema + ".board_board (name) VALUES ('shipped') RETURNING id").Scan(&board); err != nil {
				return err
			}
			_, err := db.Exec("INSERT INTO "+schema+".outbox_job (kind, payload, run_at, created_at) VALUES ('post_published', '{\"title\":\"shipped\"}', now(), now()), ('export_files', $1, now(), now()), ('nope', '{}', now(), now())", fmt.Sprintf(`{"id":%d}`, board))
			return err
		}); err != nil {
			return err
		}
		store := s3fake.New(t)
		const orphan = "0123456789abcdef0123456789abcdef" // a key no row has
		s3fake.Touch(store, orphan, time.Now().Add(-48*time.Hour))
		env = append(env, "BOARD_S3_ENDPOINT="+store.Endpoint, "BOARD_S3_REGION="+store.Region, "BOARD_S3_BUCKET="+store.Bucket,
			"BOARD_S3_ACCESS_KEY_ID="+store.AccessKeyID, "BOARD_S3_SECRET_ACCESS_KEY="+store.SecretAccessKey)
		heard := make(chan string, 1)
		hook := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			select {
			case heard <- r.Header.Get("Authorization"):
			default:
			}
		}))
		defer hook.Close()
		env = append(env, "BOARD_WEBHOOK_URL="+hook.URL, "BOARD_WEBHOOK_TOKEN=s3cret")
		use = func(string) error {
			select {
			case got := <-heard:
				if got != "Bearer s3cret" {
					return fmt.Errorf("the webhook heard Authorization %q", got)
				}
			case <-time.After(10 * time.Second):
				return fmt.Errorf("the webhook heard nothing of the outbox's job in 10s")
			}
			// Then, within 10 seconds, the files and the job of no kind.
			var err error
			for deadline := time.Now().Add(10 * time.Second); time.Now().Before(deadline); time.Sleep(100 * time.Millisecond) {
				if err = shipped(t, schema, board, store, orphan); err == nil {
					break
				}
			}
			return err
		}
	}
	return serve(root, bin, "/app/", http.StatusOK, env, true, use)
}

// shipped is nil once the job of kind nope has failed, the worker has
// written board's export to store, and the sweep has deleted orphan from
// it.
func shipped(t *testing.T, schema string, board int64, store s3.Store, orphan string) error {
	var failed, key string
	if err := withPostgres(func(db *sql.DB) error {
		return db.QueryRow("SELECT last_error FROM " + schema + ".outbox_job WHERE kind = 'nope'").Scan(&failed)
	}); err != nil || failed == "" {
		return fmt.Errorf("the job of kind nope is gone, or has no error, after 10s: %v", err)
	}
	if err := withPostgres(func(db *sql.DB) error {
		return db.QueryRow("SELECT key FROM "+schema+".board_export_file WHERE board_id = $1 AND name = 'index.md'", board).Scan(&key)
	}); err != nil {
		return fmt.Errorf("no export file of board %d in 10s: %v", board, err)
	}
	f, err := store.Open(t.Context(), key)
	if err != nil {
		return fmt.Errorf("no export file %s in the bucket in 10s: %v", key, err)
	}
	f.Close()
	if f, err = store.Open(t.Context(), orphan); !errors.Is(err, fs.ErrNotExist) {
		if err == nil {
			f.Close()
		}
		return fmt.Errorf("the orphan %s is still in the bucket after 10s: %v", orphan, err)
	}
	return nil
}

// refuse runs bin in root with env, on any free port, and wants it to stop
// by itself within 10 seconds, before it listens, with a status other than
// 0 and want in what it says.
func refuse(root, bin string, env []string, want string) error {
	var out bytes.Buffer
	cmd := osexec.Command(bin)
	cmd.Dir = root
	cmd.Env = append(append(os.Environ(), "PORT=0"), env...)
	cmd.Stdout, cmd.Stderr = &out, &out
	if err := cmd.Start(); err != nil {
		return err
	}
	exited := make(chan error, 1)
	go func() { exited <- cmd.Wait() }()
	select {
	case err := <-exited:
		if err == nil || !strings.Contains(out.String(), want) || strings.Contains(out.String(), "listening on") {
			return fmt.Errorf("%v, want it to stop with %q:\n%s", err, want, out.String())
		}
		return nil
	case <-time.After(10 * time.Second):
		cmd.Process.Kill()
		<-exited
		return fmt.Errorf("still running after 10s, want it to stop with %q:\n%s", want, out.String())
	}
}

// serve runs bin in root on a free PORT until path answers want, for 10
// seconds at most, then runs use, if not nil, against it, and stops it
// before it returns: the walk's schema goes after, which a pool still open
// would hold.
func serve(root, bin, path string, want int, env []string, graceful bool, use func(base string) error) error {
	l, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		return err
	}
	port := strconv.Itoa(l.Addr().(*net.TCPAddr).Port)
	l.Close() // another process may take it in between: rare, and the error names the port
	var out bytes.Buffer
	cmd := osexec.Command(bin)
	cmd.Dir = root
	cmd.Env = append(append(os.Environ(), "PORT="+port), env...)
	cmd.Stdout, cmd.Stderr = &out, &out
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("serve: %v", err)
	}
	exited := make(chan struct{})
	go func() { cmd.Wait(); close(exited) }()
	base := "http://127.0.0.1:" + port
	client := http.Client{Timeout: time.Second, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}
	up, died := false, false
wait:
	for deadline := time.Now().Add(10 * time.Second); time.Now().Before(deadline); {
		select {
		case <-exited:
			died = true
			break wait
		case <-time.After(100 * time.Millisecond):
		}
		if resp, err := client.Get(base + path); err == nil {
			resp.Body.Close()
			if up = resp.StatusCode == want; up {
				break
			}
		}
	}
	if up && use != nil {
		err = use(base)
	}
	stopped := true
	if graceful { // as a platform stops it: SIGTERM, then exit 0
		cmd.Process.Signal(syscall.SIGTERM)
		select {
		case <-exited:
			stopped = cmd.ProcessState.Success()
		case <-time.After(35 * time.Second):
			stopped = false
		}
	}
	cmd.Process.Kill()
	<-exited // out is the server's no more
	switch {
	case died:
		return fmt.Errorf("serve: %s stopped before %s answered (PORT=%s):\n%s", filepath.Base(bin), path, port, out.String())
	case !up:
		return fmt.Errorf("serve: no %d from %s in 10s (PORT=%s):\n%s", want, path, port, out.String())
	case err != nil:
		return fmt.Errorf("serve: %v\nthe server said:\n%s", err, out.String())
	case !stopped:
		return fmt.Errorf("serve: SIGTERM did not stop %s with status 0:\n%s", filepath.Base(bin), out.String())
	}
	return nil
}

// toPostgres moves the walk at root to a new schema of MAAGO_TEST_PG_URL's
// server, as a reader moves to PostgreSQL by .env: once, and without a
// server, a skip, or a failure in CI (D-91).
func toPostgres(t *testing.T, root, schema string, n int) (string, error) {
	if schema != "" || n > 1 {
		return "", fmt.Errorf("Maago-Database: postgres twice")
	}
	server := os.Getenv("MAAGO_TEST_PG_URL")
	switch {
	case server != "":
	case os.Getenv("CI") != "":
		return "", fmt.Errorf("MAAGO_TEST_PG_URL is not set; CI must run the PostgreSQL tests")
	default:
		t.Skip("MAAGO_TEST_PG_URL is not set; set it to a PostgreSQL server to run this test")
	}
	// Named by the test, so the next run drops what a killed one left.
	schema = maagotest.SchemaName("github.com/maago-web/maago/cmd/maago board walk", t.Name(), 0)
	if err := withPostgres(func(db *sql.DB) error {
		_, err := db.Exec("DROP SCHEMA IF EXISTS " + schema + " CASCADE; CREATE SCHEMA " + schema)
		return err
	}); err != nil {
		return "", err
	}
	t.Cleanup(func() {
		if err := withPostgres(func(db *sql.DB) error {
			_, err := db.Exec("SET lock_timeout = '5s'; DROP SCHEMA IF EXISTS " + schema + " CASCADE")
			return err
		}); err != nil {
			t.Errorf("cannot drop schema %s: %v", schema, err)
		}
	})
	u, err := url.Parse(server)
	if err != nil {
		return "", fmt.Errorf("MAAGO_TEST_PG_URL does not parse")
	}
	q := u.Query()
	q.Set("search_path", schema)
	u.RawQuery = q.Encode()
	writeFile(t, filepath.Join(root, ".env"), "MAAGO_DATABASE_URL="+u.String()+"\n")
	return schema, nil
}

// withPostgres runs f on MAAGO_TEST_PG_URL's server.
func withPostgres(f func(*sql.DB) error) error {
	db, err := sql.Open("pgx", os.Getenv("MAAGO_TEST_PG_URL"))
	if err != nil {
		return err
	}
	defer db.Close()
	return f(db)
}

// goCmd is the go command in root, offline, on root's go.work.
func goCmd(root string, args ...string) *osexec.Cmd {
	cmd := osexec.Command("go", args...)
	cmd.Dir = root
	cmd.Env = append(os.Environ(),
		// These win over the environment's own: exec.Cmd uses the last
		// value of a key.
		"GOWORK="+filepath.Join(root, "go.work"),
		"GOPROXY=off",           // the module cache only: cmd/maago's tests fetched the same versions
		"GOFLAGS=-mod=readonly", // a stale go.sum fails, whatever GOFLAGS says
	)
	return cmd
}

func walkStep(root, patch string, tr trailers) error {
	want := tr.want
	// What maago add writes is not in the patch, as generated files are
	// not: the step runs it first, as its reader did.
	for _, app := range tr.apps {
		if _, ds := scaffold.Add(root, app); ds != nil {
			return fmt.Errorf("maago add %s:\n%s", app, text(ds))
		}
	}
	abs, _ := filepath.Abs(patch)
	apply := osexec.Command("git", "apply", abs)
	apply.Dir = root
	if out, err := apply.CombinedOutput(); err != nil {
		return fmt.Errorf("git apply: %v\n%s", err, out)
	}

	_, ds := build.Gen(root)
	got := diagnostics(text(ds))
	if want != nil {
		if !slices.Equal(slices.Sorted(slices.Values(got)), slices.Sorted(slices.Values(want))) {
			return fmt.Errorf("maago gen: expected\n%s\ngot\n%s", strings.Join(want, "\n"), text(ds))
		}
		lines := strings.Split(text(ds), "\n")
		for i := range lines {
			lines[i] = strings.TrimSpace(lines[i])
		}
		for _, fix := range tr.fixes {
			if !slices.Contains(lines, fix) {
				return fmt.Errorf("maago gen: the message quotes\n%s\ngot\n%s", fix, text(ds))
			}
		}
		return nil
	}
	if ds != nil {
		return fmt.Errorf("maago gen:\n%s", text(ds))
	}
	if out, err := osexec.Command("gofmt", "-l", root).CombinedOutput(); err != nil || len(out) > 0 {
		return fmt.Errorf("gofmt -l: %v\n%s", err, out)
	}
	if ds := build.Check(root); ds != nil {
		return fmt.Errorf("maago check:\n%s", text(ds))
	}
	if _, ds := build.Migrate(root); ds != nil {
		return fmt.Errorf("maago migrate:\n%s", text(ds))
	}
	// The app's tests find the root's .env from their package's directory,
	// as a reader's do (D-113): no address is given them.
	if out, err := goCmd(root, "test", "./...").CombinedOutput(); err != nil {
		return fmt.Errorf("go test: %v\n%s", err, out)
	}
	return nil
}

// trailers are what a step's commit message asks of the walk.
type trailers struct {
	want, apps []string // Maago-Expect:, Maago-Run: maago add
	fixes      []string // the fix: lines the message quotes
	postgres   int      // Maago-Database: postgres lines
}

// expected reads the trailers of a patch's commit message, which ends
// where the diff starts (steps.sh packs without a diffstat): the
// Maago-Expect: lines, the apps of Maago-Run: maago add APP lines, which
// the step runs before its patch, and Maago-Database: postgres, which moves
// the walk to PostgreSQL before it. The mail header before it has no
// Maago- lines. A step with Maago-Expect: lines quotes the fix: lines of
// its diagnostics as maago gen writes them, each on one line: the walk
// finds each among gen's lines.
func expected(patch []byte) (tr trailers, err error) {
	msg, _, ok := strings.Cut(string(patch), "\ndiff --git ")
	if !ok {
		return tr, fmt.Errorf("no diff after the commit message")
	}
	for _, line := range strings.Split(msg, "\n") {
		switch {
		case strings.HasPrefix(strings.TrimSpace(line), "fix: "):
			tr.fixes = append(tr.fixes, strings.TrimSpace(line))
		case strings.HasPrefix(line, "Maago-Expect: "):
			tr.want = append(tr.want, strings.TrimPrefix(line, "Maago-Expect: "))
		case strings.HasPrefix(line, "Maago-Run: maago add ") && !strings.ContainsAny(strings.TrimPrefix(line, "Maago-Run: maago add "), " \t") && line != "Maago-Run: maago add ":
			tr.apps = append(tr.apps, strings.TrimPrefix(line, "Maago-Run: maago add "))
		case line == "Maago-Database: postgres":
			tr.postgres++
		case strings.HasPrefix(line, "Maago-"):
			return tr, fmt.Errorf("unknown trailer %q; maago knows Maago-Expect:, Maago-Run: maago add APP and Maago-Database: postgres", line)
		}
	}
	return tr, nil
}
