func TestPGReadByHand(t *testing.T) {
	url := pgURL(t)
	src, err := os.ReadFile("../../internal/dialect/postgres/testdata/example.sql")
	if err != nil {
		t.Fatal(err)
	}
	read := func(src string) string {
		db := openPractice(t, project.Postgres, url)
		apply(t, db, src)
		s, ds := postgres.Read(ctx(t), db)
		if len(ds) > 0 {
			t.Fatalf("Read:\n%s", text(ds))
		}
		return formatSchema(s, false)
	}
	if a, b := read(string(src)), read(pgExampleByHand); a != b {
		t.Errorf("read differently:\n%s\nby hand:\n%s", a, b)
	}
}

// A table of the same name in public is not read (the practice schema is
// the only one on search_path, D-96). The public table is made inside the
// practice transaction, so it is rolled back with it.
