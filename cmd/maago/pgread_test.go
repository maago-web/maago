// readPG applies src to a new practice schema and reads it back.
func readPG(t *testing.T, url, src string) string {
	t.Helper()
	db := openPractice(t, project.Postgres, url)
	apply(t, db, src)
	s, ds := postgres.Read(ctx(t), db)
	out := text(ds)
	if s != nil {
		out = formatSchema(s, true) + out
	}
	return out
}

func TestPGReadExample(t *testing.T) {
	url := pgURL(t)
	src, err := os.ReadFile("../../internal/dialect/postgres/testdata/example.sql")
	if err != nil {
		t.Fatal(err)
	}
	golden.Check(t, "testdata/pg_example.golden", []byte(readPG(t, url, string(src))))
}

