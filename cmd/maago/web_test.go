package main

import (
	"os"
	osexec "os/exec"
	"path/filepath"
	"testing"

	"github.com/maago-web/maago/internal/build"
)

// webProject copies the fixture project testdata/web to a new directory
// with a go.work that points at this repository, and makes maago and go
// use it: the same module graph for the type check of maago gen and for
// go test (D-117).
func webProject(t *testing.T) string {
	t.Helper()
	root, err := filepath.EvalSymlinks(t.TempDir()) // go compares go.work's directory with the real path
	if err != nil {
		t.Fatal(err)
	}
	if err := os.CopyFS(root, os.DirFS("testdata/web")); err != nil {
		t.Fatal(err)
	}
	repo, err := filepath.EvalSymlinks("../..")
	if err == nil {
		repo, err = filepath.Abs(repo)
	}
	if err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(root, "go.work"), "go 1.25.0\n\nuse .\n\nreplace github.com/maago-web/maago => "+repo+"\n")
	t.Setenv("GOWORK", filepath.Join(root, "go.work"))
	t.Setenv("GOPROXY", "off") // the module cache only: this module's tests fetched the same versions
	t.Setenv("MAAGO_DATABASE_URL", "sqlite:app.db")
	return root
}

// TestWeb generates the adapters of the fixture app, checks that check
// then passes, and runs the app's own test, which makes requests: bad
// path values and sql.ErrNoRows are 404, bad queries 400, a POST view
// redirects, an API route answers JSON, a failed render writes nothing.
func TestWeb(t *testing.T) {
	root := webProject(t)
	if _, ds := build.Gen(root); ds != nil {
		t.Fatalf("maago gen:\n%s", text(ds))
	}
	if ds := build.Check(root); ds != nil {
		t.Fatalf("maago check after gen:\n%s", text(ds))
	}
	test := osexec.Command("go", "test", "./...")
	test.Dir = root
	test.Env = append(os.Environ(), "GOFLAGS=-mod=readonly")
	if out, err := test.CombinedOutput(); err != nil {
		t.Fatalf("go test: %v\n%s", err, out)
	}
}

// A stale views_gen.go that names a view the project no longer has does
// not stop gen: the type check sees the new one.
func TestWebStaleViews(t *testing.T) {
	root := webProject(t)
	writeFile(t, filepath.Join(root, "site", "views_gen.go"), "// Code generated by maago. DO NOT EDIT.\n\npackage site\n\nvar _ = Gone\n")
	if _, ds := build.Gen(root); ds != nil {
		t.Fatalf("maago gen:\n%s", text(ds))
	}
}

// A user's type error shows, with its place, and hides the view checks
// that would follow from it.
func TestWebTypeError(t *testing.T) {
	root := webProject(t)
	writeFile(t, filepath.Join(root, "site", "bad.go"), "package site\n\nvar X int = \"x\"\n")
	_, ds := build.Gen(root)
	want := "site/bad.go:3:13: cannot use \"x\" (untyped string constant) as int value in variable declaration\n  fix: go build reports the same error; fix it there\n"
	if got := text(ds); got != want {
		t.Errorf("got\n%s", got)
	}
}

// A project without routes is not type-checked, so maago runs without the
// go command (D-117).
func TestNoRoutesNoGo(t *testing.T) {
	root := webProject(t)
	if err := os.Remove(filepath.Join(root, "site", "urls.go")); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", "")
	if _, ds := build.Gen(root); ds != nil {
		t.Fatalf("maago gen:\n%s", text(ds))
	}
}
